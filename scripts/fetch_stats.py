"""Fetch profile numbers from the GitHub GraphQL API into data/stats.json.

Runs in GitHub Actions. With a personal access token (secret GH_STATS_TOKEN)
the telemetry card also counts private repositories and the repositories of
organizations the account belongs to; without
it, the workflow's own token is used and only public data is counted.

The language card only ever uses public repositories owned by the account,
so it reflects the code people can actually open.
"""
import json
import os
import urllib.request
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Repositories left out of the language breakdown (old crypto/bootcamp experiments).
EXCLUDE_REPOS = {
    "automated-transaction-on-balance-threshold", "ethereum-wallet-interactor", "chainteanode",
    "teaprotocol", "solanaproject", "solana-bootcamp-final-project",
    "solidity-bnb-chain-development-bootcamp-final-project",
}
# Platform scaffolding generated by Flutter and similar tooling, not hand-written code.
EXCLUDE_LANGS = {
    "C++", "C", "CMake", "Swift", "Objective-C", "Kotlin", "Ruby", "Batchfile", "Shell",
    "PowerShell", "Makefile", "Dockerfile", "HTML", "CSS", "Rust", "Solidity",
}

QUERY = """
query($login: String!, $cursor: String) {
  user(login: $login) {
    followers { totalCount }
    contributionsCollection {
      totalCommitContributions
      contributionCalendar { totalContributions }
    }
    organizations(first: 20) {
      nodes {
        login
        repositories(first: 100, isFork: false) {
          totalCount
          nodes { stargazerCount }
        }
      }
    }
    repositories(first: 100, after: $cursor, isFork: false, ownerAffiliations: [OWNER]) {
      totalCount
      pageInfo { hasNextPage endCursor }
      nodes {
        name
        isPrivate
        owner { login }
        stargazerCount
        languages(first: 10, orderBy: {field: SIZE, direction: DESC}) {
          edges { size node { name } }
        }
      }
    }
  }
}
"""


def gql(token, variables):
    req = urllib.request.Request(
        "https://api.github.com/graphql",
        data=json.dumps({"query": QUERY, "variables": variables}).encode(),
        headers={"Authorization": f"bearer {token}", "Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req) as resp:
        payload = json.load(resp)
    if "errors" in payload:
        raise SystemExit(payload["errors"])
    return payload["data"]["user"]


def main():
    token = os.environ["GH_STATS_TOKEN"]
    login = os.environ.get("PROFILE_LOGIN", "akalnengn")
    cursor, repos, viewer = None, [], None
    while True:
        viewer = gql(token, {"login": login, "cursor": cursor})
        page = viewer["repositories"]
        repos += page["nodes"]
        if not page["pageInfo"]["hasNextPage"]:
            break
        cursor = page["pageInfo"]["endCursor"]

    langs = Counter()
    for repo in repos:
        if repo["isPrivate"] or repo["owner"]["login"].lower() != login.lower():
            continue
        if repo["name"].lower() in EXCLUDE_REPOS or repo["name"].lower() == login.lower():
            continue
        for edge in repo["languages"]["edges"]:
            name = edge["node"]["name"]
            if name not in EXCLUDE_LANGS:
                langs[name] += edge["size"]

    orgs = viewer["organizations"]["nodes"]
    org_repo_count = sum(o["repositories"]["totalCount"] for o in orgs)
    org_stars = sum(r["stargazerCount"] for o in orgs for r in o["repositories"]["nodes"])

    contrib = viewer["contributionsCollection"]
    data = {
        "stars": sum(r["stargazerCount"] for r in repos) + org_stars,
        "contributions": contrib["contributionCalendar"]["totalContributions"],
        "commits": contrib["totalCommitContributions"],
        "repositories": viewer["repositories"]["totalCount"] + org_repo_count,
        "followers": viewer["followers"]["totalCount"],
        "languages": langs.most_common(5),
    }
    out = ROOT / "data" / "stats.json"
    out.parent.mkdir(exist_ok=True)
    out.write_text(json.dumps(data, indent=2) + "\n")
    print(json.dumps(data))


if __name__ == "__main__":
    main()
